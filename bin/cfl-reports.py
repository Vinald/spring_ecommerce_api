import datetime
import smtplib
import sys
from prettytable import PrettyTable
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

sys.path.append('..')
from app.core import database
from app.utilities.Email import mail_host, mail_port, username, password, email_from

connection = database.get_conn()
cursor = database.get_cursor()


def apps():
    sql = "SELECT name FROM `apps`"
    cursor.execute(sql)
    results = cursor.fetchall()
    return results


def yesterday(app_name):
    sql = "select id from cdr where app_name = '{}' and call_state = 'ANSWERED' and DATE(creation_date) = DATE_SUB(DATE(now()), INTERVAL 1 DAY)"
    cursor.execute(sql.format(app_name))
    return cursor.rowcount


def last_week(app_name):
    sql = "select id from cdr where app_name = '{}' and call_state = 'ANSWERED' and DATE(creation_date) = DATE_SUB(DATE(now()), INTERVAL 8 DAY)"
    cursor.execute(sql.format(app_name))
    return cursor.rowcount


test_apps = ["Motech Inhouse IVR", "default", "CFL LITE HIV Staging", "CFL Covid Surveillance Staging"]

today = datetime.date.today()
day_name = (today - datetime.timedelta(days=1)).strftime("%a")

pt = PrettyTable(["App Name", "{}".format(day_name), "Last {}".format(day_name), "Diff"])

for app in apps():
    app_name = app['name']
    if app_name not in test_apps:
        yesterday_count = int(yesterday(app_name))
        last_week_count = int(last_week(app_name))
        difference = yesterday_count - last_week_count

        if difference > 0:
            difference = "+{}".format(difference)

        # app_lengths.append(len(app_name))
        pt.add_row([app_name, yesterday_count, last_week_count, difference])


