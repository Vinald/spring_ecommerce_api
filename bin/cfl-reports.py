msg.attach(part1)
msg.attach(part2)


server = smtplib.SMTP(mail_host, mail_port)

try:
    server.starttls()
    server.login(username, password)
    server.sendmail(email_from, 'nkidhoma@idi.co.ug', msg.as_string())
    print("Email sent")
except Exception as e:
    print("Failed to send email with error: {}".format(e))
finally:
    server.quit()
